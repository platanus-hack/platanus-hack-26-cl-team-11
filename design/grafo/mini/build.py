"""Build the offline graph with the same embedded Stage and assets as its full scenes."""
import json
import sys
from pathlib import Path
from importlib.util import module_from_spec, spec_from_file_location

HERE = Path(__file__).resolve().parent
DESIGN = HERE.parents[1]
sys.dont_write_bytecode = True
spec = spec_from_file_location("ronda_motion", DESIGN / "motion/src/build.py")
motion = module_from_spec(spec)
spec.loader.exec_module(motion)

js, css = motion.bundle(HERE / "network.jsx")
styles = "\n".join((css, (DESIGN / "tokens.css").read_text(), (DESIGN / "ronda.css").read_text(), (HERE / "network.css").read_text()))
faces = {name: motion.asset("faces/" + name + ".png", "image/png") for name in ["mati","ian","lian","andres","roberto"]}
license_text = (DESIGN.parent / ".agents/skills/stageshow/LICENSE").read_text()
page = f'''<!doctype html>
<!-- Generated by design/grafo/mini/build.py. Stageshow license:
{license_text}
-->
<html lang="es-CL"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Interacciones en paralelo · Ronda</title><link rel="icon" href="{motion.LOGO}" type="image/svg+xml">
<style>{styles}</style></head><body><div class="rd-page"><div class="rd-aura" aria-hidden="true"><i></i><i></i><i></i><i></i></div>
<div class="rd-page__inner frame"><header class="rd-bar"><div class="brand-note"><span class="rd-brand"><img class="rd-mark" src="{motion.LOGO}" alt="">Ronda</span><span class="rd-note">Red de agentes</span></div>
<button class="rd-button rd-button--quiet" id="toggle" type="button"><svg viewBox="0 0 16 16" aria-hidden="true"><path class="pause-icon" d="M3 2h3v12H3zm7 0h3v12h-3z"/><path class="play-icon" d="m3 1 11 7-11 7z"/></svg><span>Pausar</span></button><span id="still" class="rd-note" hidden>Movimiento reducido</span></header>
<main><h1 class="rd-hero stage-title">Interacciones en paralelo</h1><div id="example" aria-label="Cinco agentes y sus intercambios"></div></main>
<footer class="note rd-note"><span>Selecciona un objeto para ver la escena completa.</span><span>Demo con datos simulados</span></footer>
</div></div><script>window.rondaFaces={json.dumps(faces)};</script><script>{js}</script></body></html>'''
(DESIGN / "motion/minis.html").write_text(page)

# The standalone studies also run alongside versions of the globe that use a
# different renderer and have no embedding markers.
if "--stage-only" in sys.argv or "// BEGIN GENERATED MINIATURES" not in (DESIGN / "grafo/globo.html").read_text():
    sys.exit(0)

# The canvas artifact runs its component in isolation. Inline the same small
# renderer in its lifecycle, including the approved colors for that sandbox.
tokens = "\n".join(line.strip() for line in (DESIGN / "tokens.css").read_text().splitlines() if line.strip().startswith("--rd-mini-"))
helpers = "\n".join((HERE / f).read_text() for f in ("calendar-edge.js", "motion-paint.js", "objects.js", "edges.js", "globe.js"))
start = "// BEGIN GENERATED MINIATURES"
end = "// END GENERATED MINIATURES"
for name, prefix in [("globo.html", "../motion/"), ("globo.dc.html", "")]:
    target = DESIGN / "grafo" / name
    text = target.read_text()
    before, embedded = text.split(start, 1)
    _, after = embedded.split(end, 1)
    setup = f"""
    {helpers}
    const controller = mountGlobeMinis(cv, {json.dumps(prefix)}, this.reduced || new URLSearchParams(location.search).has('still'));
    cv.nextElementSibling.style.cssText += {json.dumps(";" + tokens)};
    return controller;
    """
    target.write_text(before + start + setup + end + after)

target = DESIGN / "grafo/globo.html"
text = target.read_text()
def replace_embedded(text, start, end, body):
    left, rest = text.split(start, 1)
    _, right = rest.split(end, 1)
    return left + start + "\n" + body + "\n" + end + right
text = replace_embedded(text, "<!-- BEGIN PORTABLE STYLES -->", "<!-- END PORTABLE STYLES -->",
    f'<link rel="icon" type="image/svg+xml" href="{motion.LOGO}"><style>' +
    (DESIGN / "tokens.css").read_text() + (DESIGN / "ronda.css").read_text() + "</style>")
text = replace_embedded(text, "/* BEGIN PORTABLE FACES */", "/* END PORTABLE FACES */",
    "    var src = " + json.dumps(list(faces.values())) + ";")
target.write_text(text)
