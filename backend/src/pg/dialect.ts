const TABLE_INFO = /^\s*PRAGMA\s+table_info\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*;?\s*$/i;
const CREATE_TABLE = /^\s*CREATE\s+TABLE\b/i;
const ALTER_TABLE = /^\s*ALTER\s+TABLE\b/i;
const INSERT_OR_IGNORE = /\bINSERT\s+OR\s+IGNORE\s+INTO\b/i;
const HAS_ROW_ID = /\bPRIMARY\s+KEY\s+AUTOINCREMENT\b|\bINTEGER\s+PRIMARY\s+KEY\b/i;
const CAMEL_CASE = /\b[a-z][a-z0-9_]*[A-Z][A-Za-z0-9_]*\b/g;

type Piece = { text: string; literal: boolean };

function piecesOf(sql: string): Piece[] {
  const pieces: Piece[] = [];
  let start = 0;
  let at = 0;
  while (at < sql.length) {
    if (sql[at] !== "'") {
      at += 1;
      continue;
    }
    if (at > start) pieces.push({ text: sql.slice(start, at), literal: false });
    let end = at + 1;
    while (end < sql.length) {
      if (sql[end] === "'" && sql[end + 1] === "'") end += 2;
      else if (sql[end] === "'") break;
      else end += 1;
    }
    pieces.push({ text: sql.slice(at, end + 1), literal: true });
    at = end + 1;
    start = at;
  }
  if (start < sql.length) pieces.push({ text: sql.slice(start), literal: false });
  return pieces;
}

const outsideLiterals = (sql: string, change: (text: string) => string) =>
  piecesOf(sql)
    .map((piece) => (piece.literal ? piece.text : change(piece.text)))
    .join('');

function statementsOf(sql: string): string[] {
  const statements: string[] = [];
  let current = '';
  for (const piece of piecesOf(sql)) {
    if (piece.literal) {
      current += piece.text;
      continue;
    }
    const parts = piece.text.split(';');
    parts.forEach((part, index) => {
      current += part;
      if (index < parts.length - 1) {
        statements.push(current);
        current = '';
      }
    });
  }
  statements.push(current);
  return statements.map((statement) => statement.trim()).filter((statement) => statement !== '');
}

function closingParenthesisOf(sql: string): number {
  let depth = 0;
  let position = 0;
  for (const piece of piecesOf(sql)) {
    if (!piece.literal) {
      for (let index = 0; index < piece.text.length; index += 1) {
        const char = piece.text[index];
        if (char === '(') depth += 1;
        if (char === ')') {
          depth -= 1;
          if (depth === 0) return position + index;
        }
      }
    }
    position += piece.text.length;
  }
  return -1;
}

const columnTypes = (text: string) =>
  text
    .replace(/\bINTEGER\s+PRIMARY\s+KEY(\s+AUTOINCREMENT)?\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bBLOB\b/gi, 'BYTEA');

const expressions = (text: string) =>
  text
    .replace(/\bIS\s+NOT\s+(?!NULL\b|TRUE\b|FALSE\b|DISTINCT\b)/gi, 'IS DISTINCT FROM ')
    .replace(/\bIS\s+(?!NOT\b|NULL\b|TRUE\b|FALSE\b|DISTINCT\b)/gi, 'IS NOT DISTINCT FROM ')
    .replace(/\bjson_each\s*\(\s*\?\s*\)/gi, 'json_array_elements_text(?::json) AS value');

function createTable(statement: string): string {
  const typed = outsideLiterals(statement, columnTypes);
  if (HAS_ROW_ID.test(statement)) return typed;
  const end = closingParenthesisOf(typed);
  return end < 0 ? typed : `${typed.slice(0, end)}, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY${typed.slice(end)}`;
}

function insertOrIgnore(statement: string): string {
  const plain = statement.replace(INSERT_OR_IGNORE, 'INSERT INTO');
  const returning = plain.search(/\bRETURNING\b/i);
  return returning < 0 ? `${plain} ON CONFLICT DO NOTHING` : `${plain.slice(0, returning)}ON CONFLICT DO NOTHING ${plain.slice(returning)}`;
}

function translated(statement: string): string {
  const tableInfo = TABLE_INFO.exec(statement);
  if (tableInfo) return `SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '${tableInfo[1]?.toLowerCase()}' ORDER BY ordinal_position`;
  if (CREATE_TABLE.test(statement)) return createTable(statement);
  if (ALTER_TABLE.test(statement)) return outsideLiterals(statement, columnTypes);
  const immediate = outsideLiterals(statement.replace(/^\s*BEGIN\s+(IMMEDIATE|EXCLUSIVE|DEFERRED)\b/i, 'BEGIN'), expressions);
  return INSERT_OR_IGNORE.test(immediate) ? insertOrIgnore(immediate) : immediate;
}

function numbered(statement: string): string {
  let position = 0;
  return outsideLiterals(statement, (text) => text.replace(/\?/g, () => `$${(position += 1)}`));
}

export const toPostgres = (sql: string): string => numbered(translated(sql.trim().replace(/;\s*$/, '')));

export const scriptToPostgres = (sql: string): string => statementsOf(sql).map(translated).join(';\n');

export const isTableInfo = (sql: string): boolean => TABLE_INFO.test(sql);

export const isInsert = (sql: string): boolean => /^\s*INSERT\b/i.test(sql);

export const hasReturning = (sql: string): boolean => piecesOf(sql).some((piece) => !piece.literal && /\bRETURNING\b/i.test(piece.text));

export function camelCaseNamesIn(sql: string): string[] {
  return piecesOf(sql).flatMap((piece) => (piece.literal ? [] : (piece.text.match(CAMEL_CASE) ?? [])));
}
