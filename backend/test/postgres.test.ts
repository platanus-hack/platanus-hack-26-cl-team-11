test('queries written for SQLite are translated to Postgres', () => {
  assert.equal(toPostgres("SELECT a FROM t WHERE b = ? AND c = '¿qué?' AND d = ?"), "SELECT a FROM t WHERE b = $1 AND c = '¿qué?' AND d = $2");
  assert.equal(toPostgres('INSERT OR IGNORE INTO t (a) VALUES (?)'), 'INSERT INTO t (a) VALUES ($1) ON CONFLICT DO NOTHING');
  assert.equal(toPostgres('INSERT OR IGNORE INTO t (a) VALUES (?) RETURNING a'), 'INSERT INTO t (a) VALUES ($1) ON CONFLICT DO NOTHING RETURNING a');
  assert.equal(toPostgres('SELECT a FROM t WHERE a IS NOT NULL AND b IS ? AND c IS NOT excluded.c'), 'SELECT a FROM t WHERE a IS NOT NULL AND b IS NOT DISTINCT FROM $1 AND c IS DISTINCT FROM excluded.c');
  assert.equal(toPostgres('SELECT a FROM t WHERE a IN (SELECT value FROM json_each(?))'), 'SELECT a FROM t WHERE a IN (SELECT value FROM json_array_elements_text($1::json) AS value)');
  assert.equal(toPostgres('BEGIN IMMEDIATE'), 'BEGIN');
  assert.match(toPostgres('PRAGMA table_info(Events)'), /information_schema\.columns .* table_name = 'events'/);
  assert.equal(
    scriptToPostgres("CREATE TABLE IF NOT EXISTS t (id INTEGER PRIMARY KEY AUTOINCREMENT, due INTEGER NOT NULL, score REAL, note TEXT DEFAULT 'a;b'); CREATE TABLE u (k TEXT PRIMARY KEY, n INTEGER CHECK (n IN (0, 1)))"),
    "CREATE TABLE IF NOT EXISTS t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, due BIGINT NOT NULL, score DOUBLE PRECISION, note TEXT DEFAULT 'a;b');\nCREATE TABLE u (k TEXT PRIMARY KEY, n BIGINT CHECK (n IN (0, 1)), rowid BIGINT GENERATED BY DEFAULT AS IDENTITY)",
  );
});

test('a Postgres database answers like the SQLite one did', () => {
  const db = openDatabase({ kind: 'memory' });
  db.exec('CREATE TABLE notes (id INTEGER PRIMARY KEY AUTOINCREMENT, ownerToken TEXT NOT NULL, due INTEGER NOT NULL, weight REAL); CREATE TABLE tags (name TEXT PRIMARY KEY)');
  const first = db.prepare('INSERT INTO notes (ownerToken, due, weight) VALUES (?, ?, ?)').run('ana', 1795297727076, 1.25);
  assert.deepEqual(first, { changes: 1, lastInsertRowid: 1 });
  assert.deepEqual(db.prepare('SELECT id, ownerToken, due, weight, weight > 1 AS heavy FROM notes WHERE id = ?').get(1), { id: 1, ownerToken: 'ana', due: 1795297727076, weight: 1.25, heavy: 1 });
  assert.deepEqual(db.prepare('SELECT COUNT(*) AS total FROM notes').get(), { total: 1 });
  assert.equal(db.prepare('SELECT id FROM notes WHERE id = ?').get(99), undefined);
  assert.equal(db.prepare('INSERT OR IGNORE INTO tags (name) VALUES (?)').run('a').changes, 1);
  assert.equal(db.prepare('INSERT OR IGNORE INTO tags (name) VALUES (?)').run('a').changes, 0);
  assert.equal(db.prepare('UPDATE notes SET weight = ? WHERE ownerToken = ?').run(2, 'ana').changes, 1);
  assert.deepEqual(
    (db.prepare('PRAGMA table_info(notes)').all() as Array<{ name: string }>).map((column) => column.name),
    ['id', 'ownerToken', 'due', 'weight'],
  );
  db.exec('BEGIN');
  db.prepare('DELETE FROM notes').run();
  db.exec('ROLLBACK');
  assert.deepEqual(db.prepare('SELECT COUNT(*) AS total FROM notes').get(), { total: 1 });
  assert.throws(() => db.prepare('INSERT INTO tags (name) VALUES (?)').run('a'), /duplicate key/);
  db.close();
});

test('the data kept in SQLite moves to Postgres once, in the same order, and new rows continue the numbering', () => {
  const location = mkdtempSync(join(tmpdir(), 'montu-import-'));
  const before = createContext({ location, model: null, whatsapp: null });
  createApp(before);
  const ana = before.store.addPerson('Ana');
  const tomas = before.store.addPerson('Tomás');
  const team = before.teams.createTeam('Vita');
  before.teams.addMember(team.id, tomas.token);
  before.teams.addMember(team.id, ana.token);
  before.store.saveConnection(ana.token, 'granola', 'ana@vita.lat', 'secreto');
  for (let day = 1; day <= 3; day += 1) {
    before.store.saveEvent(ana.token, { source: 'apple_health', type: 'salud_diaria', occurredAt: `2026-11-0${day}`, summary: `sueño ${day}`, raw: { day }, externalId: `dia:${day}` });
  }
  const sealedOf = (db: typeof before.db) => db.prepare('SELECT account, secret_sealed FROM connections WHERE person_token = ?').get(ana.token);
  const sealed = { ...sealedOf(before.db) };
  const eventsBefore = before.store.listEvents(ana.token, 10);
  before.db.close();

  const after = createContext({ location: ':memory:', model: null, whatsapp: null });
  createApp(after);
  const report = importFromSqlite(after.db, join(location, SQLITE_FILE));
  assert.ok(report);
  assert.deepEqual(
    report.tables.filter((table) => table.problems.length > 0 || table.copied !== table.found),
    [],
  );
  assert.match(describeImport(report)[0] ?? '', /^Importación desde SQLite: \d+ de \d+ filas/);
  assert.ok((report.backupBytes ?? 0) > 0);

  assert.equal(after.store.findPerson(ana.token)?.name, 'Ana');
  assert.deepEqual(
    after.teams.membersOf(team.id).map((member) => member.name),
    ['Tomás', 'Ana'],
  );
  assert.deepEqual(after.store.listEvents(ana.token, 10), eventsBefore);
  assert.deepEqual(sealedOf(after.db), sealed);

  const added = after.store.saveEvent(ana.token, { source: 'apple_health', type: 'salud_diaria', occurredAt: '2026-11-04', summary: 'sueño 4', raw: {}, externalId: 'dia:4' });
  assert.ok((added?.id ?? 0) > Math.max(...eventsBefore.map((event) => event.id)));
  assert.equal(importFromSqlite(after.db, join(location, SQLITE_FILE)), null);
});
